package config

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func asJSON(t *testing.T, c Config) string {
	t.Helper()
	b, err := json.Marshal(c)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// The new LoadConfig must build exactly what the old one built, for the same file.
func TestLoadConfigUnchanged(t *testing.T) {
	example, err := os.ReadFile("../../config.json.example")
	if err != nil {
		t.Fatal(err)
	}
	cases := map[string]string{
		"example":   string(example),
		"empty":     `{}`,
		"comments":  "{\n // a comment\n \"metrics_port\": 9090, \"torrentio_url\": \"https://x.example\"\n}",
		"uppercase": `{"Plex": {"Token": "tok", "URL": "http://plex:32400"}, "MetricsPort": 9091}`,
		"wrongtype": `{"metrics_port":"9091","fuse_mount_path":"/mnt/x","physical_source_path":"/src"}`,
	}
	// A real config.json, checked by hand: TIRAMISU_EQUIV_CONFIG=/path go test -run TestLoadConfigUnchanged
	if p := os.Getenv("TIRAMISU_EQUIV_CONFIG"); p != "" {
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		cases["real"] = string(b)
	}
	for name, body := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			p := filepath.Join(dir, "config.json")
			os.WriteFile(p, []byte(body), 0600)
			t.Setenv("MKV_PROXY_CONFIG_PATH", p)
			t.Setenv("MKV_PROXY_CONCURRENCY", "7")
			oldC, newC := legacyLoadConfig(), LoadConfig()
			if a, b := asJSON(t, oldC), asJSON(t, newC); a != b {
				t.Fatalf("JSON differs:\nold %s\nnew %s", a, b)
			}
			if oldC.LogDir != newC.LogDir || oldC.ConfigPath != newC.ConfigPath || oldC.ReadAheadBudget != newC.ReadAheadBudget {
				t.Fatalf("derived fields differ: %q/%q %q/%q", oldC.LogDir, newC.LogDir, oldC.ConfigPath, newC.ConfigPath)
			}
		})
	}
}

func TestLoadConfigNeverWrites(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "config.json")
	t.Setenv("MKV_PROXY_CONFIG_PATH", p)
	c := LoadConfig()
	if _, err := os.Stat(p); err == nil {
		t.Fatal("LoadConfig created config.json: a drop-in would re-import defaults")
	}
	if c.TelemetryID != "" {
		t.Fatal("the telemetry ID is generated by Bootstrap, not LoadConfig")
	}
}

func TestDocumentCanonicalAndEnvFree(t *testing.T) {
	doc, err := ParseDocument([]byte(`{"Plex": {"Token": "tok"}, "master_concurrency_limit": 30}`))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(doc), `"plex"`) || !strings.Contains(string(doc), `"token": "tok"`) {
		t.Fatalf("not canonical: %s", doc)
	}
	t.Setenv("MKV_PROXY_CONCURRENCY", "7")
	stored, _ := Resolve(doc, Env{WithEnv: false})
	inUse, _ := Resolve(doc, Env{WithEnv: true})
	if stored.MasterConcurrencyLimit != 30 || inUse.MasterConcurrencyLimit != 7 {
		t.Fatalf("env handling: stored=%d inUse=%d", stored.MasterConcurrencyLimit, inUse.MasterConcurrencyLimit)
	}
	again, _ := Canonical(doc)
	if string(again) != string(doc) {
		t.Fatal("canonical document must round-trip unchanged")
	}
	d2, _ := Canonical([]byte(`{"blocklist_filter": "a // b"}`))
	c2, _ := Resolve(d2, Env{})
	if c2.BlockListFilter != "a // b" {
		t.Fatalf("string truncated: %q", c2.BlockListFilter)
	}
	if _, err := ParseDocument([]byte(`[1,2]`)); err == nil {
		t.Fatal("a JSON array is not a configuration")
	}
	if _, err := ParseDocument([]byte(`{"metrics_port": "x"}`)); err == nil {
		t.Fatal("a field of the wrong type must be refused")
	}
}
